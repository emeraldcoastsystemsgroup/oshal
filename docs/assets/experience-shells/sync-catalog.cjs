// Mechanical snapshot of the real store. Only writes the generated mockup data file.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const yaml = require('js-yaml');
const store = path.resolve(process.argv[2] || path.join(__dirname, '../../../../oshal-applications'));
const input = fs.readFileSync(path.join(store, 'marketplace.json'), 'utf8');
const marketplace = JSON.parse(input);
const apps = marketplace.apps.map(app => {
 const manifest = yaml.load(fs.readFileSync(path.join(store, app.source.path, 'oshal-app.yaml'), 'utf8'));
 const optional = manifest.dependencies?.optional?.apps || [];
 const required = manifest.dependencies?.required?.apps || [];
 const depName = dependency => typeof dependency === 'string' ? dependency : dependency.name;
 return {
  id: app.name, name: app.displayName, suite: app.suite, description: app.description,
  version: app.version, packagePath: app.source.path, catalogStatus: app.status,
  bots: (manifest.bots || []).map(bot => bot.name).filter(Boolean),
  chatBot: manifest.chatBot || null,
  required: required.map(depName).filter(Boolean), optional: optional.map(depName).filter(Boolean)
 };
});
const snapshot = {
 source: 'oshal-applications/marketplace.json + package manifests',
 sourceCommit: execFileSync('git', ['rev-parse', 'HEAD'], { cwd: store, encoding: 'utf8' }).trim(),
 catalogSha256: crypto.createHash('sha256').update(input).digest('hex'),
 capturedAt: new Date().toISOString(), apps
};
fs.writeFileSync(path.join(__dirname, 'catalog-data.js'), '// Generated by sync-catalog.cjs. Catalog facts only; runtime state is not asserted.\nwindow.OSHAL_CATALOG = ' + JSON.stringify(snapshot, null, 2) + ';\n');
console.log(`Captured ${apps.length} real catalog entries in ${new Set(apps.map(app => app.suite)).size} suites.`);
